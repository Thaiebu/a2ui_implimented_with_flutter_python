import os
import json
import re
from datetime import datetime
from pathlib import Path
from typing import List, Dict, Any, Optional

SAVED_APPS_DIR = Path(__file__).resolve().parent.parent.parent / "saved_apps"
SAVED_APPS_DIR.mkdir(parents=True, exist_ok=True)

def sanitize_filename(name: str) -> str:
    slug = re.sub(r'[^a-zA-Z0-9_-]', '_', name.strip().lower())
    return slug[:40] or "untitled_app"

def save_app_to_disk(
    app_id: str,
    name: str,
    components: List[Dict[str, Any]],
    data: Dict[str, Any],
    history: List[Dict[str, str]]
) -> Dict[str, Any]:
    file_id = sanitize_filename(app_id or name)
    file_path = SAVED_APPS_DIR / f"{file_id}.json"

    payload = {
        "id": file_id,
        "name": name,
        "updated_at": datetime.utcnow().isoformat(),
        "component_count": len(components),
        "components": components,
        "data": data,
        "history": history
    }

    with open(file_path, "w", encoding="utf-8") as f:
        json.dump(payload, f, indent=2)

    return payload

def list_saved_apps() -> List[Dict[str, Any]]:
    apps = []
    if not SAVED_APPS_DIR.exists():
        return apps

    for p in SAVED_APPS_DIR.glob("*.json"):
        try:
            with open(p, "r", encoding="utf-8") as f:
                data = json.load(f)
                apps.append({
                    "id": data.get("id", p.stem),
                    "name": data.get("name", p.stem.title()),
                    "updated_at": data.get("updated_at", ""),
                    "component_count": data.get("component_count", len(data.get("components", [])))
                })
        except Exception:
            continue

    # Sort descending by updated_at
    apps.sort(key=lambda x: x.get("updated_at", ""), reverse=True)
    return apps

def load_saved_app(app_id: str) -> Optional[Dict[str, Any]]:
    file_path = SAVED_APPS_DIR / f"{app_id}.json"
    if not file_path.exists():
        return None

    try:
        with open(file_path, "r", encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return None

def delete_saved_app(app_id: str) -> bool:
    file_path = SAVED_APPS_DIR / f"{app_id}.json"
    if file_path.exists():
        file_path.unlink()
        return True
    return False

